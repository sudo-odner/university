data class FinanceExtendedColors(
    val income: Color,
    val expense: Color,
    val orange: Color,
    val purple: Color
)

val LocalFinanceExtendedColors = staticCompositionLocalOf {
    FinanceExtendedColors(
        income = FinanceGreenLight,
        expense = FinanceRedLight,
        orange = FinanceOrangeLight,
        purple = FinancePurpleLight
    )
}

val MaterialTheme.financeColors: FinanceExtendedColors
    @Composable
    get() = LocalFinanceExtendedColors.current

@Composable
fun FinanceAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val extendedColors = if (darkTheme) {
        FinanceExtendedColors(
            income = FinanceGreenDark,
            expense = FinanceRedDark,
            orange = FinanceOrangeDark,
            purple = FinancePurpleDark
        )
    } else {
        FinanceExtendedColors(
            income = FinanceGreenLight,
            expense = FinanceRedLight,
            orange = FinanceOrangeLight,
            purple = FinancePurpleLight
        )
    }

    CompositionLocalProvider(LocalFinanceExtendedColors provides extendedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = FinanceTypography,
            shapes = FinanceShapes,
            content = content
        )
    }
}
